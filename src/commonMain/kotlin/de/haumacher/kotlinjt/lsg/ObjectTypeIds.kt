/**
 * The Object Type Identifier table of Annex A (Table A.1): the single source of truth mapping
 * an element's Object Type ID GUID to its element type. The LSG codecs dispatch on it, and
 * the inventory uses it to name elements in any segment kind.
 *
 * GUIDs are written exactly as the annex prints them: `data1, data2, data3` follow the file
 * byte order, the eight tail bytes do not.
 */
object ObjectTypeIds {
    private fun guid(
        d1: Long,
        d2: Int,
        d3: Int,
        vararg tail: Int,
    ): Guid {
        require(tail.size == 8)
        return Guid(d1.toUInt(), d2.toUShort(), d3.toUShort(), ByteArray(8) { tail[it].toByte() }.toBytes())
    }

